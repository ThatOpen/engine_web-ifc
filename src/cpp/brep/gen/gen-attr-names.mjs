// Generates ifc_attr_names.inc: for every schema web-ifc knows, each entity's type code, class name and
// its attributes in argument order (the order of the typed constructor, which is how web-ifc's own
// GetLine maps raw arguments to named fields).
//   node gen-attr-names.mjs <ifc-schema.ts> <out.inc>
import { readFileSync, writeFileSync } from "node:fs";

const [src, out] = process.argv.slice(2);
const text = readFileSync(src, "utf8");
const blocks = [];
const re = /^export namespace (\w+) \{/gm;
let m;
const starts = [];
while ((m = re.exec(text))) starts.push({ name: m[1], at: m.index });
for (let i = 0; i < starts.length; i++) blocks.push({ name: starts[i].name, body: text.slice(starts[i].at, i + 1 < starts.length ? starts[i + 1].at : text.length) });

const lines = ["// generated by gen-attr-names.mjs — do not edit", "// { schema, typeCode, \"Name\", { \"Attr\", ... } }"];
for (const b of blocks) {
  // Parent of every class, abstract ones included, so subtype queries can be answered.
  const parentOf = new Map([...b.body.matchAll(/export class (\w+) extends (\w+)/g)].map((x) => [x[1], x[2]]));
  const cls = /export class (\w+) extends \w+ \{\s*type:number=(\d+);(?:\s*\w+!:[^\n]*)*\s*constructor\(/g;
  let c, n = 0;
  while ((c = cls.exec(b.body))) {
    const [, name, code] = c;
    const chain = [];
    for (let p = parentOf.get(name); p && p.startsWith("Ifc") && chain.length < 40; p = parentOf.get(p)) chain.push(p);
    // The parameter list nests parentheses in its types, so walk to the matching one.
    let depth = 1, i = cls.lastIndex;
    while (depth > 0 && i < b.body.length) { const ch = b.body[i++]; if (ch === "(") depth++; else if (ch === ")") depth--; }
    const params = b.body.slice(cls.lastIndex, i - 1);
    const attrs = [...params.matchAll(/public (\w+)\s*:/g)].map((x) => x[1]);
    lines.push(`{ "${b.name}", ${code}u, "${name}", { ${attrs.map((a) => `"${a}"`).join(", ")} }, { ${chain.map((a) => `"${a}"`).join(", ")} } },`);
    n++;
  }
  console.error(b.name, n);
}
writeFileSync(out, lines.join("\n") + "\n");
